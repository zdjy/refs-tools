export function getColorTheme(dark: boolean): GlobalThemeOverrides {
  return toNaiveTheme(getAdminPalette(dark));
}

/**
 * 登录页沿用 FS-0009 的中性配色例外：品牌色不使用篮球场红。
 * 形状、尺寸、焦点环与管理端保持一致，不构成第三套主题。
 */
export function getLoginColorTheme(dark: boolean): GlobalThemeOverrides {
  const palette = getLoginPalette(dark);
  const theme = toNaiveTheme(palette);
  return {
    ...theme,
    common: {
      ...theme.common,
      errorColor: palette.danger,
      errorColorHover: palette.dangerHover,
      errorColorPressed: palette.dangerHover,
      errorColorSuppl: palette.danger,
    },
    Button: {
      ...theme.Button,
      borderRadiusLarge: '6px',
    },
    Input: {
      ...theme.Input,
      boxShadowFocus: dark ? '0 0 0 3px rgb(250 248 245 / 12%)' : '0 0 0 3px rgb(17 17 17 / 8%)',
    },
    InternalSelection: {
      ...theme.InternalSelection,
      boxShadowActive: dark ? '0 0 0 3px rgb(250 248 245 / 12%)' : '0 0 0 3px rgb(17 17 17 / 8%)',
      boxShadowFocus: dark ? '0 0 0 3px rgb(250 248 245 / 12%)' : '0 0 0 3px rgb(17 17 17 / 8%)',
    },
  };
}
